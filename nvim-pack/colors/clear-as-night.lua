function M.setup()
    vim.cmd("highlight clear")
    vim.o.termguicolors = true
    vim.g.colors_name = "clear-as-night"

    for group, settings in pairs(groups) do
        vim.api.nvim_set_hl(0, group, settings)
    end
end

M.setup()

return M

